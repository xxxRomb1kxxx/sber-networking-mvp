export function buildEvents() {
  return raw.map((e) => {
    const startsAt = at(e.days, e.hour, e.minute || 0);
    return {
      id: e.id,
      title: e.title,
      summary: e.summary,
      description: e.description,
      format: e.format,
      place: e.place,
      hostId: e.hostId,
      startsAt,
      endsAt: plusMinutes(startsAt, e.durationMin),
      seats: e.seats,
      topics: e.topics,
      agenda: e.agenda,
      createdAt: new Date().toISOString(),
    };
  });
}

/**
 * Занятые места и переписка демо-участников.
 * Номера мест идут подряд — ровно в том порядке, в котором «регистрировались».
 */
export function buildEventSeed() {
  const registrations = [];
  const messages = [];
  let seq = 0;

  for (const e of raw) {
    const startsAt = new Date(at(e.days, e.hour, e.minute || 0));
    e.takenBy.slice(0, e.seats).forEach((userId, i) => {
      registrations.push({
        id: `reg-${e.id}-${i + 1}`,
        eventId: e.id,
        userId,
        seatNo: i + 1,
        // Регистрации «случились» до мероприятия, по убыванию давности.
        createdAt: new Date(startsAt.getTime() - (e.takenBy.length - i) * 3600 * 1000 * 6).toISOString(),
      });
    });

    for (const m of e.chat) {
      seq += 1;
      messages.push({
        id: `evm-${seq}`,
        eventId: e.id,
        authorId: m.by,
        text: m.text,
        createdAt: new Date(Date.now() - m.minsAgo * 60000).toISOString(),
      });
    }
  }

  return { registrations, messages };
}
